const { chromium } = require("../tools/mcp/node_modules/playwright");
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const credentials = fs.readFileSync(".local-admin/login.txt", "utf8");
const username = credentials.match(/Tài khoản: (.+)/)[1].trim();
const password = credentials.match(/Mật khẩu: (.+)/)[1].trim();
const base = "http://127.0.0.1:5173";
(async () => {
  const browser = await chromium.launch({ headless:true, channel:"msedge" });
  const errors = [], report = [];
  const c = await browser.newContext({ viewport:{width:1440,height:1000} });
  try {
    const p = await c.newPage();
    p.on("pageerror", e => errors.push(e.message));
    assert.equal((await c.request.get(base+"/api/admin/draft")).status(),401);
    assert.equal((await c.request.put(base+"/api/admin/draft",{data:{}})).status(),401);
    for (const url of ["/.local-admin/login.txt", "/@fs/D:/lovely-gift/.local-admin/credentials.json", "/%2elocal-admin/login.txt"]) {
      assert.equal((await c.request.get(base+url)).status(),403);
    }
    await p.goto(base+"/admin");
    await p.getByLabel("Tài khoản",{exact:true}).fill(username);
    await p.getByLabel("Mật khẩu",{exact:true}).fill("incorrect");
    await p.getByRole("button",{name:"Đăng nhập",exact:true}).click();
    await p.getByRole("alert").waitFor();
    await p.getByLabel("Mật khẩu",{exact:true}).fill(password);
    await p.getByRole("button",{name:"Đăng nhập",exact:true}).click();
    await p.getByRole("heading",{name:"Tổng quan",exact:true}).waitFor();
    const original = await (await c.request.get(base+"/api/admin/draft")).json();
    const fixture = JSON.parse(fs.readFileSync("public/content/site.json","utf8"));
    fixture.events[0].recipients[0].account = "Nguyễn Linh 01/01/2000";
    fixture.events[0].recipients[0].name = "Linh";
    try {
      assert.equal((await c.request.put(base+"/api/admin/draft",{data:fixture})).status(),200);
      await p.reload();
      await p.getByRole("button",{name:"Sự kiện",exact:true}).click();
      // Real WAV fixture generated by the media QA; upload another valid WAV twice.
      const wav = Buffer.alloc(44+8000*2); wav.write("RIFF");wav.writeUInt32LE(wav.length-8,4);wav.write("WAVEfmt ",8);wav.writeUInt32LE(16,16);wav.writeUInt16LE(1,20);wav.writeUInt16LE(1,22);wav.writeUInt32LE(8000,24);wav.writeUInt32LE(16000,28);wav.writeUInt16LE(2,32);wav.writeUInt16LE(16,34);wav.write("data",36);wav.writeUInt32LE(wav.length-44,40);
      const upload = p.getByLabel("Nhạc nền",{exact:true});
      await upload.setInputFiles({name:"song-one.wav",mimeType:"audio/wav",buffer:wav});
      await p.locator("audio").waitFor();
      const first = await p.locator("audio").getAttribute("src");
      wav.writeInt16LE(1200,44);
      await upload.setInputFiles({name:"song-two.wav",mimeType:"audio/wav",buffer:wav});
      await p.waitForFunction(first => document.querySelector("audio").src !== first,first);
      await p.getByText("Bản nháp đã lưu trên máy",{exact:true}).waitFor();
      await p.reload();
      await p.getByRole("button",{name:"Sự kiện",exact:true}).click();
      assert.notEqual(await p.locator("audio").getAttribute("src"),first);
      report.push("Admin password login, denied anonymous draft access, private files blocked, two music uploads and server persistence");
      await p.getByRole("button",{name:"Đăng xuất",exact:true}).click();
      await p.getByRole("button",{name:"Đăng nhập",exact:true}).waitFor();
      assert.equal((await c.request.get(base+"/api/admin/draft")).status(),401);
      report.push("Logout invalidates server session");
    } finally {
      await c.request.post(base+"/api/admin/login",{data:{username,password}});
      if(original) await c.request.put(base+"/api/admin/draft",{data:original});
      else await c.request.delete(base+"/api/admin/draft");
      await c.request.post(base+"/api/admin/logout");
    }
    await c.route("**/content/site.json",route=>route.fulfill({json:fixture}));
    await p.goto(base);
    assert.equal(await p.getByRole("button",{name:"Quản trị",exact:true}).count(),0);
    for (const selector of [".header-note",".occasion",".welcome-bottom",".site-footer",".art-caption",".scene-progress"]) assert.equal(await p.locator(selector).count(),0);
    await p.getByLabel("Nhận lời chúc gửi tới bạn 💗",{exact:true}).fill("Nguyễn Linh 01/01/2000");
    await p.getByRole("button",{name:"Tìm thiệp của tôi"}).click();
    await p.getByRole("heading").filter({hasText:"Gửi Linh"}).waitFor();
    assert.equal(await p.locator(".open-hint").count(),0);
    await p.getByRole("button",{name:"Mở phong thư",exact:true}).click({force:true});
    await p.getByRole("button",{name:"Mở sổ lời chúc",exact:true}).click();
    await p.locator(".book-cover").click();
    assert(await p.locator(".cover-opening").count());
    await p.locator(".book-spread").waitFor();
    await p.locator(".book-spread").click();
    assert(await p.locator(".turn-sheet").count());
    await p.waitForTimeout(200);
    assert.notEqual(await p.locator(".turn-sheet").evaluate(el => getComputedStyle(el).transform), "none");
    await p.screenshot({path:"artifacts/qa/book-turn.png"});
    await p.waitForTimeout(750);
    while(await p.getByRole("button",{name:"Trang tiếp",exact:true}).count()) {
      await p.getByRole("button",{name:"Trang tiếp",exact:true}).click();
      await p.waitForTimeout(750);
    }
    await p.locator(".book-spread").click();
    await p.locator(".garden-dock").waitFor();
    assert.equal(await p.locator(".garden-heading .eyebrow,.garden-heading p").count(),0);
    fs.mkdirSync("artifacts/qa",{recursive:true});
    await p.screenshot({path:"artifacts/qa/revised-garden.png"});
    report.push("Recipient login differs from display name; removed subtitles; automatic click navigation, opening cover and flipping pages");
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.resolve("artifacts/qa/revision-report.json"),JSON.stringify({report,errors},null,2));
    console.log(JSON.stringify({report,errors},null,2));
  } finally { await c.close(); await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
